"""Service layer for audit_log."""
from atlas.adapters.audit_sink import AuditSink


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class AuditTrail:
    """Every mutating call is appended to AuditTrail and flushed to the append-only AuditSink.

    The heavy lifting happens in AuditSink.write (atlas/adapters/audit_sink.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = AuditSink()

    def append(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "audit_log")
        outcome = self._backend.write(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "audit_log")
        return outcome


def _audit_trail_pass_1(items, *, limit=58):
    """Annotate marker in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("marker"):
            out.append(("marker", i, item["marker"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


