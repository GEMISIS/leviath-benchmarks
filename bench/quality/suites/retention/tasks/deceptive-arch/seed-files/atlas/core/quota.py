"""Service layer for quota_meter."""
from atlas.adapters.usage_store import UsageStore


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class QuotaService:
    """Document submission is gated by QuotaService, which meters every accepted request into UsageStore keyed by tenant and day.

    The heavy lifting happens in UsageStore.add (atlas/adapters/usage_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = UsageStore()

    def check_and_count(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "quota_meter")
        outcome = self._backend.add(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "quota_meter")
        return outcome


class _QuotaLedger1:
    """Tracks bucket occupancy for callers in this package."""

    def __init__(self, capacity=116):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _quota_pass_2(items, *, limit=37):
    """Reconcile frame in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("frame"):
            out.append(("frame", i, item["frame"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


