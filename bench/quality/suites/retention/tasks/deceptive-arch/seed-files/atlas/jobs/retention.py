"""Entry points around retention_sweep."""
from atlas.core.retention import RetentionPlanner


def run_retention_sweep(payload, ctx, cfg=None):
    """The retention sweep plans deletions with RetentionPlanner and executes them against ObjectStore.

    Delegates to RetentionPlanner.plan (atlas/core/retention.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = RetentionPlanner(cfg)
    result = service.plan(payload, ctx)
    return result


def _retention_pass_1(items, *, limit=83):
    """Normalize lease in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 3) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("lease"):
            out.append(("lease", i, item["lease"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


