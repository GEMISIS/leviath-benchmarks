    """Concrete backend for the usage_rollup pathway family."""

    def __init__(self, namespace="usage_rollup"):
        self.namespace = namespace
        self._rows = []

    def merge(self, payload):
        row = {"ns": self.namespace, "op": "merge",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "merge",
                "rows": len(self._rows)}


