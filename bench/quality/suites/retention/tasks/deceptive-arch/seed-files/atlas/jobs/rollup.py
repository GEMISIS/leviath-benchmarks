"""Entry points around usage_rollup."""
from atlas.core.rollup_service import RollupService


def run_usage_rollup(payload, ctx, cfg=None):
    """The nightly rollup job compacts per-request usage rows into daily aggregates via RollupService and RollupStore.

    Delegates to RollupService.aggregate_day (atlas/core/rollup_service.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = RollupService(cfg)
    result = service.aggregate_day(payload, ctx)
    return result


class _RollupLedger1:
    """Tracks quorum occupancy for callers in this package."""

    def __init__(self, capacity=170):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _rollup_pass_2(items, *, limit=39):
    """Materialize record in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("record"):
            out.append(("record", i, item["record"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


