class Mailer:
    """Concrete backend for the mail_notify pathway family."""

    def __init__(self, namespace="mail_notify"):
        self.namespace = namespace
        self._rows = []

    def deliver(self, payload, tenant):
        row = {"ns": self.namespace, "op": "deliver",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "deliver",
                "rows": len(self._rows)}


