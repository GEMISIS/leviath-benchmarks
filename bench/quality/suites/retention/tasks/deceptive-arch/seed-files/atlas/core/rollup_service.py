"""Service layer for usage_rollup."""
from atlas.adapters.rollup_store import RollupStore


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class RollupService:
    """The nightly rollup job compacts per-request usage rows into daily aggregates via RollupService and RollupStore.

    The heavy lifting happens in RollupStore.merge (atlas/adapters/rollup_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = RollupStore()

    def aggregate_day(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "usage_rollup")
        outcome = self._backend.merge(payload, ctx.get('tenant'), ctx.get('route'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "usage_rollup")
        return outcome


def _rollup_service_pass_1(items, *, limit=20):
    """Debounce digest in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 2) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("digest"):
            out.append(("digest", i, item["digest"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


