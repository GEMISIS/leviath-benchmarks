class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class SessionBroker:
    """Authentication opens a session through SessionBroker, persisted in SessionStore with a sliding expiry.

    The heavy lifting happens in SessionStore.put (atlas/adapters/session_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = SessionStore()

    def open(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "auth_session")
        outcome = self._backend.put(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "auth_session")
        return outcome


