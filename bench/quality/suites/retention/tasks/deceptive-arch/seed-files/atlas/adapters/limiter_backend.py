class TokenBucketBackend:
    """Concrete backend for the throttle_gate pathway family."""

    def __init__(self, namespace="throttle_gate"):
        self.namespace = namespace
        self._rows = []

    def reserve(self, payload, tenant):
        row = {"ns": self.namespace, "op": "reserve",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "reserve",
                "rows": len(self._rows)}


