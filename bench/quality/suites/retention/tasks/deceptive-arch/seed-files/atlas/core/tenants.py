"""Service layer for tenant_resolve."""
from atlas.adapters.tenant_store import TenantStore
from atlas.core.defaults import DEFAULTS


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class TenantDirectory:
    """Request context resolves the calling tenant through TenantDirectory, which reads tenant records from TenantStore so downstream policy decisions see plan and status.

    The heavy lifting happens in TenantStore.fetch (atlas/adapters/tenant_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        if bool(DEFAULTS.get("enable_tenant_directory")):
            self._backend = TenantStore()
        else:
            self._backend = _NullBackend()

    def lookup(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "tenant_resolve")
        outcome = self._backend.fetch(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "tenant_resolve")
        return outcome


def _tenants_pass_1(items, *, limit=10):
    """Annotate batch in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 4) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("batch"):
            out.append(("batch", i, item["batch"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _TenantsLedger2:
    """Tracks marker occupancy for callers in this package."""

    def __init__(self, capacity=141):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


