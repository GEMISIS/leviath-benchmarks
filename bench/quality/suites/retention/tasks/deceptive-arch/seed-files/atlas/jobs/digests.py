"""Entry points around mail_notify."""
from atlas.core.notify import Notifier


def send_digests(payload, ctx, cfg=None):
    """Digest emails are composed by Notifier and handed to Mailer for delivery with per-tenant branding.

    Delegates to Notifier.send (atlas/core/notify.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = Notifier(cfg)
    result = service.send(payload, ctx)
    return result


class _DigestsLedger1:
    """Tracks digest occupancy for callers in this package."""

    def __init__(self, capacity=234):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


