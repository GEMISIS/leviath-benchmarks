"""Entry points around tenant_resolve."""
from atlas.core.tenants import TenantDirectory


def resolve_tenant(payload, ctx, cfg=None):
    """Request context resolves the calling tenant through TenantDirectory, which reads tenant records from TenantStore so downstream policy decisions see plan and status.

    Delegates to TenantDirectory.lookup (atlas/core/tenants.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = TenantDirectory(cfg)
    result = service.lookup(payload, ctx)
    return result


class _ContextLedger1:
    """Tracks manifest occupancy for callers in this package."""

    def __init__(self, capacity=250):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


