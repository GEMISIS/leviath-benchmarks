"""Entry points around audit_log."""
from atlas.core.audit_trail import AuditTrail


def audit_middleware(payload, ctx, cfg=None):
    """Every mutating call is appended to AuditTrail and flushed to the append-only AuditSink.

    Delegates to AuditTrail.append (atlas/core/audit_trail.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = AuditTrail(cfg)
    result = service.append(payload, ctx)
    return result


def _audit_pass_1(items, *, limit=41):
    """Reconcile shard in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("shard"):
            out.append(("shard", i, item["shard"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _AuditLedger2:
    """Tracks epoch occupancy for callers in this package."""

    def __init__(self, capacity=126):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


