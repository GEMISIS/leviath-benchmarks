"""Service layer for limits_policy."""
from atlas.adapters.config_source import ConfigSource


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class LimitPolicy:
    """Per-tenant limit policies are produced by LimitPolicy, which layers tenant overrides from ConfigSource over the shipped defaults.

    The heavy lifting happens in ConfigSource.read (atlas/adapters/config_source.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ConfigSource()

    def for_tenant(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "limits_policy")
        outcome = self._backend.read(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "limits_policy")
        return outcome


def _limits_pass_1(items, *, limit=34):
    """Prune window in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("window"):
            out.append(("window", i, item["window"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


