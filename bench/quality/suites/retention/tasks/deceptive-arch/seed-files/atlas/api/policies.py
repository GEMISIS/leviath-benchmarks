"""Entry points around limits_policy."""
from atlas.core.limits import LimitPolicy


def effective_policy(payload, ctx, cfg=None):
    """Per-tenant limit policies are produced by LimitPolicy, which layers tenant overrides from ConfigSource over the shipped defaults.

    Delegates to LimitPolicy.for_tenant (atlas/core/limits.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = LimitPolicy(cfg)
    result = service.for_tenant(payload, ctx)
    return result


class _PoliciesLedger1:
    """Tracks manifest occupancy for callers in this package."""

    def __init__(self, capacity=133):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _policies_pass_2(items, *, limit=39):
    """Interleave cursor in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("cursor"):
            out.append(("cursor", i, item["cursor"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


