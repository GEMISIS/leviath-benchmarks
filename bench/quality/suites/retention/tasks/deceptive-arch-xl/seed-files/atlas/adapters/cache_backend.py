class ShardedCache:
    """Concrete backend for the cache_gate pathway family."""

    def __init__(self, namespace="cache_gate"):
        self.namespace = namespace
        self._rows = []

    def get(self, payload, tenant):
        row = {"ns": self.namespace, "op": "get",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "get",
                "rows": len(self._rows)}


