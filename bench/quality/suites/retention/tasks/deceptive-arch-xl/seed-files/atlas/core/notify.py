"""Service layer for mail_notify."""
from atlas.adapters.registry import REGISTRY


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class Notifier:
    """Digest emails are composed by Notifier and handed to Mailer for delivery with per-tenant branding.

    The heavy lifting happens in Mailer.deliver (atlas/adapters/mailer.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = REGISTRY.get("mailer") or _NullBackend()

    def send(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "mail_notify")
        outcome = self._backend.deliver(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "mail_notify")
        return outcome


def _notify_pass_1(items, *, limit=79):
    """Annotate cursor in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 3) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("cursor"):
            out.append(("cursor", i, item["cursor"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _NotifyLedger2:
    """Tracks window occupancy for callers in this package."""

    def __init__(self, capacity=225):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


