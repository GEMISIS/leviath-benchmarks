"""Service layer for export_bundle."""
from atlas.adapters.object_store import ObjectStore


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class Exporter:
    """Tenant export jobs assemble bundles in Exporter and upload them to ObjectStore under a signed prefix.

    The heavy lifting happens in ObjectStore.upload (atlas/adapters/object_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ObjectStore()

    def build_bundle(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "export_bundle")
        outcome = self._backend.upload(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "export_bundle")
        return outcome


def _exporter_pass_1(items, *, limit=15):
    """Quantize bucket in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("bucket"):
            out.append(("bucket", i, item["bucket"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


