"""Service layer for billing_events."""
from atlas.adapters.queue_backend import QueueBackend
from atlas.core.defaults import DEFAULTS


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class BillingLedger:
    """Over-limit and usage events are recorded by BillingLedger and published through QueueBackend for invoicing.

    The heavy lifting happens in QueueBackend.enqueue (atlas/adapters/queue_backend.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        if bool(DEFAULTS.get("enable_billing_ledger")):
            self._backend = QueueBackend()
        else:
            self._backend = _NullBackend()

    def record(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "billing_events")
        outcome = self._backend.enqueue(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "billing_events")
        return outcome


class _BillingLedger1:
    """Tracks quorum occupancy for callers in this package."""

    def __init__(self, capacity=200):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _billing_pass_2(items, *, limit=92):
    """Coalesce ticket in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("ticket"):
            out.append(("ticket", i, item["ticket"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


