"""Service layer for search_index."""
from atlas.adapters.search_backend import SearchBackend


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class Indexer:
    """Document changes are indexed by Indexer, which upserts denormalized rows into SearchBackend.

    The heavy lifting happens in SearchBackend.upsert (atlas/adapters/search_backend.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = SearchBackend()

    def index(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "search_index")
        outcome = self._backend.upsert(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "search_index")
        return outcome


class _IndexerLedger1:
    """Tracks manifest occupancy for callers in this package."""

    def __init__(self, capacity=129):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


