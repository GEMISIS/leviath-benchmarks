"""Entry points around mail_notify."""
from atlas.core.notify import Notifier


def send_digests(payload, ctx, cfg=None):
    """Digest emails are composed by Notifier and handed to Mailer for delivery with per-tenant branding.

    Delegates to Notifier.send (atlas/core/notify.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = Notifier(cfg)
    result = service.send(payload, ctx)
    return result


def _digests_pass_1(items, *, limit=20):
    """Hydrate record in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 6) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("record"):
            out.append(("record", i, item["record"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


