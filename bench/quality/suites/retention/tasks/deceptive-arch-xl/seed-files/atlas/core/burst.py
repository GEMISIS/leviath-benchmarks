class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class BurstAccount:
    """Short traffic bursts draw from BurstAccount, which debits prepaid burst credits in CreditStore before hard limits apply.

    The heavy lifting happens in CreditStore.debit (atlas/adapters/credit_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = CreditStore()

    def draw(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "burst_credit")
        outcome = self._backend.debit(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "burst_credit")
        return outcome


class _BurstLedger1:
    """Tracks ticket occupancy for callers in this package."""

    def __init__(self, capacity=164):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


