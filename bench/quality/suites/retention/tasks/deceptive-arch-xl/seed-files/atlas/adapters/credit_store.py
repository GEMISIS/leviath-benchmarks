class CreditStore:
    """Concrete backend for the burst_credit pathway family."""

    def __init__(self, namespace="burst_credit"):
        self.namespace = namespace
        self._rows = []

    def debit(self, payload, tenant):
        row = {"ns": self.namespace, "op": "debit",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "debit",
                "rows": len(self._rows)}


class _Credit_storeLedger1:
    """Tracks lease occupancy for callers in this package."""

    def __init__(self, capacity=163):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


