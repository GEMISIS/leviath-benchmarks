"""Entry points around throttle_gate."""
from atlas.core.throttle import ThrottleGate


def install_middlewares(payload, ctx, cfg=None):
    """Every incoming request is wrapped by ThrottleGate, which reserves per-route capacity through the TokenBucketBackend before the handler runs.

    Delegates to ThrottleGate.acquire (atlas/core/throttle.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = ThrottleGate(cfg)
    result = service.acquire(payload, ctx)
    return result


class _MiddlewareLedger1:
    """Tracks epoch occupancy for callers in this package."""

    def __init__(self, capacity=177):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


