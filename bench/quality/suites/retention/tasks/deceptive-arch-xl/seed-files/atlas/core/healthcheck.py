"""Service layer for health_probe."""
from atlas.adapters.probe_kit import ProbeKit


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class HealthCheck:
    """The deep health endpoint fans out through HealthCheck to per-dependency probes in ProbeKit.

    The heavy lifting happens in ProbeKit.probe (atlas/adapters/probe_kit.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ProbeKit()

    def run_all(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "health_probe")
        outcome = self._backend.probe(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "health_probe")
        return outcome


class _HealthcheckLedger1:
    """Tracks shard occupancy for callers in this package."""

    def __init__(self, capacity=69):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


