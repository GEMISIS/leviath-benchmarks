"""Entry points around auth_session."""
from atlas.core.sessions import SessionBroker


def authenticate(payload, ctx, cfg=None):
    """Authentication opens a session through SessionBroker, persisted in SessionStore with a sliding expiry.

    Delegates to SessionBroker.open (atlas/core/sessions.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = SessionBroker(cfg)
    result = service.open(payload, ctx)
    return result


class _AuthLedger1:
    """Tracks shard occupancy for callers in this package."""

    def __init__(self, capacity=255):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _auth_pass_2(items, *, limit=67):
    """Hydrate epoch in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 6) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("epoch"):
            out.append(("epoch", i, item["epoch"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


