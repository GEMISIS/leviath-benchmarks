"""Adapter backends: SessionStore."""


class SessionStore:
    """Concrete backend for the auth_session pathway family."""

    def __init__(self, namespace="auth_session"):
        self.namespace = namespace
        self._rows = []

    def put(self, payload, tenant):
        row = {"ns": self.namespace, "op": "put",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "put",
                "rows": len(self._rows)}


