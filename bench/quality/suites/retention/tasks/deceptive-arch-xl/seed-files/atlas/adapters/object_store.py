"""Adapter backends: ObjectStore."""


class ObjectStore:
    """Concrete backend for the export_bundle pathway family."""

    def __init__(self, namespace="export_bundle"):
        self.namespace = namespace
        self._rows = []

    def upload(self, payload, tenant):
        row = {"ns": self.namespace, "op": "upload",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "upload",
                "rows": len(self._rows)}

    def delete(self, payload, tenant):
        row = {"ns": self.namespace, "op": "delete",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "delete",
                "rows": len(self._rows)}

    def head_object(self, payload):
        row = {"ns": self.namespace, "op": "head_object",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "head_object",
                "rows": len(self._rows)}


