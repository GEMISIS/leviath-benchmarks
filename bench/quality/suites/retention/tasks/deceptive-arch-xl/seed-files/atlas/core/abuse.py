"""Service layer for abuse_guard."""
from atlas.adapters.registry import REGISTRY


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class AbuseGuard:
    """Abusive traffic is scored by AbuseGuard, which persists strikes in StrikeStore feeding the limiter's penalty tier.

    The heavy lifting happens in StrikeStore.add_strike (atlas/adapters/strike_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = REGISTRY.get("strike_store") or _NullBackend()

    def evaluate(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "abuse_guard")
        outcome = self._backend.add_strike(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "abuse_guard")
        return outcome


def _abuse_pass_1(items, *, limit=36):
    """Checkpoint record in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 2) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("record"):
            out.append(("record", i, item["record"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


