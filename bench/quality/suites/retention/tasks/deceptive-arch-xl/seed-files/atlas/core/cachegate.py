"""Service layer for cache_gate."""
from atlas.adapters.cache_backend import ShardedCache
from atlas.core.defaults import DEFAULTS


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class CacheGate:
    """Read paths go through CacheGate, which serves hot documents from ShardedCache and falls through to storage on miss.

    The heavy lifting happens in ShardedCache.get (atlas/adapters/cache_backend.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        if bool(DEFAULTS.get("enable_cache_gate")):
            self._backend = ShardedCache()
        else:
            self._backend = _NullBackend()

    def get_or_load(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "cache_gate")
        outcome = self._backend.get(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "cache_gate")
        return outcome


class _CachegateLedger1:
    """Tracks window occupancy for callers in this package."""

    def __init__(self, capacity=40):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _cachegate_pass_2(items, *, limit=31):
    """Annotate bucket in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 3) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("bucket"):
            out.append(("bucket", i, item["bucket"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


