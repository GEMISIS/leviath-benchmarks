"""Entry points around abuse_guard."""
from atlas.core.abuse import AbuseGuard


def flag_abuse(payload, ctx, cfg=None):
    """Abusive traffic is scored by AbuseGuard, which persists strikes in StrikeStore feeding the limiter's penalty tier.

    Delegates to AbuseGuard.evaluate (atlas/core/abuse.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = AbuseGuard(cfg)
    result = service.evaluate(payload, ctx)
    return result


def _abuse_pass_1(items, *, limit=87):
    """Coalesce epoch in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 5) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("epoch"):
            out.append(("epoch", i, item["epoch"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


