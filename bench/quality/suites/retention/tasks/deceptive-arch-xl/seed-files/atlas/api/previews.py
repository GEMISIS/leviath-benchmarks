"""Entry points around doc_preview."""
from atlas.core.previews import PreviewBuilder


def render_preview(payload, ctx, cfg=None):
    """Document previews are built by PreviewBuilder and rasterized on the RenderFarm.

    Delegates to PreviewBuilder.build (atlas/core/previews.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = PreviewBuilder(cfg)
    result = service.build(payload, ctx)
    return result


def _previews_pass_1(items, *, limit=30):
    """Partition shard in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 3) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("shard"):
            out.append(("shard", i, item["shard"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


