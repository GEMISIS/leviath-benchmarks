"""Service layer for webhook_sign."""
from atlas.adapters.registry import REGISTRY


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class WebhookSigner:
    """Outbound webhooks are signed by WebhookSigner using the active key from KeyRing.

    The heavy lifting happens in KeyRing.current (atlas/adapters/key_ring.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = REGISTRY.get("key_ring") or _NullBackend()

    def sign(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "webhook_sign")
        outcome = self._backend.current(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "webhook_sign")
        return outcome


def _signing_pass_1(items, *, limit=85):
    """Partition epoch in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("epoch"):
            out.append(("epoch", i, item["epoch"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _SigningLedger2:
    """Tracks segment occupancy for callers in this package."""

    def __init__(self, capacity=29):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


