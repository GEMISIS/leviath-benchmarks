class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class PlanCatalog:
    """Tenant plan tiers resolve through PlanCatalog, which reads canonical plan rows from PlanStore.

    The heavy lifting happens in PlanStore.get_row (atlas/adapters/plan_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = PlanStore()

    def resolve(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "plan_catalog")
        outcome = self._backend.get_row(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "plan_catalog")
        return outcome


class _PlansLedger1:
    """Tracks digest occupancy for callers in this package."""

    def __init__(self, capacity=86):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _plans_pass_2(items, *, limit=93):
    """Checkpoint digest in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 2) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("digest"):
            out.append(("digest", i, item["digest"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


