"""Entry points around burst_credit."""
from atlas.core.burst import BurstAccount


def draw_burst(payload, ctx, cfg=None):
    """Short traffic bursts draw from BurstAccount, which debits prepaid burst credits in CreditStore before hard limits apply.

    Delegates to BurstAccount.draw (atlas/core/burst.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = BurstAccount(cfg)
    result = service.draw(payload, ctx)
    return result


class _BurstLedger1:
    """Tracks digest occupancy for callers in this package."""

    def __init__(self, capacity=193):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


