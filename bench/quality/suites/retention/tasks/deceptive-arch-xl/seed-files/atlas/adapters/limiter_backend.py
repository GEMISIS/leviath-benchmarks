class TokenBucketBackend:
    """Concrete backend for the throttle_gate pathway family."""

    def __init__(self, namespace="throttle_gate"):
        self.namespace = namespace
        self._rows = []

    def reserve(self, payload):
        row = {"ns": self.namespace, "op": "reserve",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "reserve",
                "rows": len(self._rows)}


class _Limiter_backendLedger1:
    """Tracks segment occupancy for callers in this package."""

    def __init__(self, capacity=127):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


