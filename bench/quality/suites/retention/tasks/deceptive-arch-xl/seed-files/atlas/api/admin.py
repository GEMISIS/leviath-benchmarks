"""Entry points around admin_overrides."""
from atlas.core.overrides import OverrideManager


def update_tenant_limits(payload, ctx, cfg=None):
    """Admin limit changes flow through OverrideManager, which validates and persists them back to ConfigSource so LimitPolicy picks them up.

    Delegates to OverrideManager.apply (atlas/core/overrides.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = OverrideManager(cfg)
    result = service.apply(payload, ctx)
    return result


class _AdminLedger1:
    """Tracks span occupancy for callers in this package."""

    def __init__(self, capacity=89):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


