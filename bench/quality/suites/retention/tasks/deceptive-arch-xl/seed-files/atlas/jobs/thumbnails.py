"""Entry points around thumbnailer."""
from atlas.core.thumbs import ThumbService


def run_thumbnails(payload, ctx, cfg=None):
    """Thumbnail jobs run through ThumbService, which resizes via ImageKit with per-tenant presets.

    Delegates to ThumbService.make (atlas/core/thumbs.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = ThumbService(cfg)
    result = service.make(payload, ctx)
    return result


class _ThumbnailsLedger1:
    """Tracks lease occupancy for callers in this package."""

    def __init__(self, capacity=184):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _thumbnails_pass_2(items, *, limit=29):
    """Checkpoint shard in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 2) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("shard"):
            out.append(("shard", i, item["shard"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


