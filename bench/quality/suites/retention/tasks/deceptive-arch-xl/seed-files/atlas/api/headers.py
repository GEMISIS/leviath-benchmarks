"""Entry points around rate_headers."""
from atlas.core.rate_view import RateView


def attach_rate_headers(payload, ctx, cfg=None):
    """Responses carry X-RateLimit headers rendered by RateView from live UsageStore snapshots.

    Delegates to RateView.snapshot (atlas/core/rate_view.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = RateView(cfg)
    result = service.snapshot(payload, ctx)
    return result


class _HeadersLedger1:
    """Tracks span occupancy for callers in this package."""

    def __init__(self, capacity=254):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _headers_pass_2(items, *, limit=51):
    """Hydrate cursor in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("cursor"):
            out.append(("cursor", i, item["cursor"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


