"""Service layer for throttle_gate."""
from atlas.adapters.limiter_backend import TokenBucketBackend


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class ThrottleGate:
    """Every incoming request is wrapped by ThrottleGate, which reserves per-route capacity through the TokenBucketBackend before the handler runs.

    The heavy lifting happens in TokenBucketBackend.reserve (atlas/adapters/limiter_backend.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = TokenBucketBackend()

    def acquire(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "throttle_gate")
        outcome = self._backend.reserve(payload, ctx.get('tenant'), ctx.get('route'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "throttle_gate")
        return outcome


def _throttle_pass_1(items, *, limit=15):
    """Coalesce shard in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("shard"):
            out.append(("shard", i, item["shard"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


