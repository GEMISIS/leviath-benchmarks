"""Entry points around plan_catalog."""
from atlas.core.plans import PlanCatalog


def get_plan(payload, ctx, cfg=None):
    """Tenant plan tiers resolve through PlanCatalog, which reads canonical plan rows from PlanStore.

    Delegates to PlanCatalog.resolve (atlas/core/plans.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = PlanCatalog(cfg)
    result = service.resolve(payload, ctx)
    return result


class _PlansLedger1:
    """Tracks segment occupancy for callers in this package."""

    def __init__(self, capacity=134):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


