"""Service layer for retention_sweep."""
from atlas.adapters.object_store import ObjectStore


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class RetentionPlanner:
    """The retention sweep plans deletions with RetentionPlanner and executes them against ObjectStore.

    The heavy lifting happens in ObjectStore.delete (atlas/adapters/object_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ObjectStore()

    def plan(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "retention_sweep")
        outcome = self._backend.delete(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "retention_sweep")
        return outcome


def _retention_pass_1(items, *, limit=18):
    """Normalize record in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 6) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("record"):
            out.append(("record", i, item["record"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


