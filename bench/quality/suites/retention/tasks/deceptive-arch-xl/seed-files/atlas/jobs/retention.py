"""Entry points around retention_sweep."""
from atlas.core.retention import RetentionPlanner


def run_retention_sweep(payload, ctx, cfg=None):
    """The retention sweep plans deletions with RetentionPlanner and executes them against ObjectStore.

    Delegates to RetentionPlanner.plan (atlas/core/retention.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = RetentionPlanner(cfg)
    result = service.plan(payload, ctx)
    return result


class _RetentionLedger1:
    """Tracks digest occupancy for callers in this package."""

    def __init__(self, capacity=218):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


