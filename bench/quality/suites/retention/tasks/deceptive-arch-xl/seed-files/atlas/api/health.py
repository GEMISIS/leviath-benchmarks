"""Entry points around health_probe."""
from atlas.core.healthcheck import HealthCheck


def deep_health(payload, ctx, cfg=None):
    """The deep health endpoint fans out through HealthCheck to per-dependency probes in ProbeKit.

    Delegates to HealthCheck.run_all (atlas/core/healthcheck.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = HealthCheck(cfg)
    result = service.run_all(payload, ctx)
    return result


class _HealthLedger1:
    """Tracks segment occupancy for callers in this package."""

    def __init__(self, capacity=235):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _health_pass_2(items, *, limit=89):
    """Normalize window in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 4) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("window"):
            out.append(("window", i, item["window"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


