"""Entry points around webhook_sign."""
from atlas.core.signing import WebhookSigner


def deliver_webhook(payload, ctx, cfg=None):
    """Outbound webhooks are signed by WebhookSigner using the active key from KeyRing.

    Delegates to WebhookSigner.sign (atlas/core/signing.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = WebhookSigner(cfg)
    result = service.sign(payload, ctx)
    return result


def _webhooks_pass_1(items, *, limit=44):
    """Interleave record in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 4) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("record"):
            out.append(("record", i, item["record"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


