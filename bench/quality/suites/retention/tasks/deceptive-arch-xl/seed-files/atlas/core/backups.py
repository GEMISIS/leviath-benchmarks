"""Service layer for backup_verify."""
from atlas.adapters.object_store import ObjectStore


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class BackupVerifier:
    """Nightly verification walks BackupVerifier over ObjectStore heads to prove restore points exist.

    The heavy lifting happens in ObjectStore.head_object (atlas/adapters/object_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ObjectStore()

    def verify(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "backup_verify")
        outcome = self._backend.head_object(payload, ctx.get('tenant'), ctx.get('route'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "backup_verify")
        return outcome


def _backups_pass_1(items, *, limit=36):
    """Partition quorum in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 7) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("quorum"):
            out.append(("quorum", i, item["quorum"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _BackupsLedger2:
    """Tracks manifest occupancy for callers in this package."""

    def __init__(self, capacity=147):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


