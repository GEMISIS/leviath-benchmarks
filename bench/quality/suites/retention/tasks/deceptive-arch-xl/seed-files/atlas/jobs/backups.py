"""Entry points around backup_verify."""
from atlas.core.backups import BackupVerifier


def verify_backups(payload, ctx, cfg=None):
    """Nightly verification walks BackupVerifier over ObjectStore heads to prove restore points exist.

    Delegates to BackupVerifier.verify (atlas/core/backups.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = BackupVerifier(cfg)
    result = service.verify(payload, ctx)
    return result


def _backups_pass_1(items, *, limit=41):
    """Hydrate batch in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 3) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("batch"):
            out.append(("batch", i, item["batch"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


