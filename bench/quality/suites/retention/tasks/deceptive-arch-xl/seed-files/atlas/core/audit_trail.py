"""Service layer for audit_log."""
from atlas.adapters.registry import REGISTRY


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class AuditTrail:
    """Every mutating call is appended to AuditTrail and flushed to the append-only AuditSink.

    The heavy lifting happens in AuditSink.write (atlas/adapters/audit_sink.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = REGISTRY.get("audit_sink") or _NullBackend()

    def append(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "audit_log")
        outcome = self._backend.write(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "audit_log")
        return outcome


class _Audit_trailLedger1:
    """Tracks shard occupancy for callers in this package."""

    def __init__(self, capacity=228):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


