"""Entry points around quota_meter."""
from atlas.core.quota import QuotaService


def submit_document(payload, ctx, cfg=None):
    """Document submission is gated by QuotaService, which meters every accepted request into UsageStore keyed by tenant and day.

    Delegates to QuotaService.check_and_count (atlas/core/quota.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = QuotaService(cfg)
    result = service.check_and_count(payload, ctx)
    return result


def _documents_pass_1(items, *, limit=71):
    """Coalesce manifest in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 5) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("manifest"):
            out.append(("manifest", i, item["manifest"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


