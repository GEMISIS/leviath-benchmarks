"""Entry points around search_index."""
from atlas.core.indexer import Indexer


def reindex_document(payload, ctx, cfg=None):
    """Document changes are indexed by Indexer, which upserts denormalized rows into SearchBackend.

    Delegates to Indexer.index (atlas/core/indexer.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = Indexer(cfg)
    result = service.index(payload, ctx)
    return result


def _search_pass_1(items, *, limit=37):
    """Reconcile frame in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("frame"):
            out.append(("frame", i, item["frame"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _SearchLedger2:
    """Tracks ticket occupancy for callers in this package."""

    def __init__(self, capacity=240):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


