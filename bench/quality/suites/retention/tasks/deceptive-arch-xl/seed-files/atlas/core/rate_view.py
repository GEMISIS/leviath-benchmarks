"""Service layer for rate_headers."""
from atlas.adapters.registry import REGISTRY


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class RateView:
    """Responses carry X-RateLimit headers rendered by RateView from live UsageStore snapshots.

    The heavy lifting happens in UsageStore.snapshot (atlas/adapters/usage_store.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = REGISTRY.get("rate_view") or _NullBackend()

    def snapshot(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "rate_headers")
        outcome = self._backend.snapshot(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "rate_headers")
        return outcome


class _Rate_viewLedger1:
    """Tracks manifest occupancy for callers in this package."""

    def __init__(self, capacity=158):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


def _rate_view_pass_2(items, *, limit=25):
    """Normalize ticket in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("ticket"):
            out.append(("ticket", i, item["ticket"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


