    """Concrete backend for the billing_events pathway family."""

    def __init__(self, namespace="billing_events"):
        self.namespace = namespace
        self._rows = []

    def enqueue(self, payload, tenant):
        row = {"ns": self.namespace, "op": "enqueue",
               "payload": str(payload)[:64]}
        self._rows.append(row)
        return {"status": "ok", "op": "enqueue",
                "rows": len(self._rows)}


