"""Service layer for thumbnailer."""
from atlas.adapters.image_kit import ImageKit


class _NullBackend:
    """Inert stand-in so callers degrade instead of raising."""

    def __getattr__(self, name):
        def _noop(*args, **kwargs):
            return {"status": "noop", "backend": "null"}
        return _noop


class ThumbService:
    """Thumbnail jobs run through ThumbService, which resizes via ImageKit with per-tenant presets.

    The heavy lifting happens in ImageKit.resize (atlas/adapters/image_kit.py); this class
    validates, shapes, and forwards.
    """

    def __init__(self, cfg=None):
        self.cfg = cfg or {}
        self._backend = ImageKit()

    def make(self, payload, ctx):
        ctx = dict(ctx or {})
        ctx.setdefault("source", "thumbnailer")
        outcome = self._backend.resize(payload, ctx.get('tenant'))
        if isinstance(outcome, dict):
            outcome.setdefault("chain", "thumbnailer")
        return outcome


