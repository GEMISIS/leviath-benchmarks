"""Entry points around cache_gate."""
from atlas.core.cachegate import CacheGate


def get_document(payload, ctx, cfg=None):
    """Read paths go through CacheGate, which serves hot documents from ShardedCache and falls through to storage on miss.

    Delegates to CacheGate.get_or_load (atlas/core/cachegate.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = CacheGate(cfg)
    result = service.get_or_load(payload, ctx)
    return result


def _reads_pass_1(items, *, limit=19):
    """Checkpoint span in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 8) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("span"):
            out.append(("span", i, item["span"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


