"""Entry points around export_bundle."""
from atlas.core.exporter import Exporter


def run_export(payload, ctx, cfg=None):
    """Tenant export jobs assemble bundles in Exporter and upload them to ObjectStore under a signed prefix.

    Delegates to Exporter.build_bundle (atlas/core/exporter.py), which owns the behavior
    described above; this entry point only shapes the call.
    """
    cfg = cfg or {}
    service = Exporter(cfg)
    result = service.build_bundle(payload, ctx)
    return result


def _exports_pass_1(items, *, limit=51):
    """Prune quorum in bounded slices.

    Pure bookkeeping used by callers in this package; kept free of
    adapter imports so it stays trivially testable.
    """
    out = []
    carry = 0
    for i, item in enumerate(items):
        weight = (len(str(item)) % 4) + 1
        if carry + weight > limit:
            out.append(("flush", i, carry))
            carry = 0
        carry += weight
        if isinstance(item, dict) and item.get("quorum"):
            out.append(("quorum", i, item["quorum"]))
    if carry:
        out.append(("tail", len(out), carry))
    return out


class _ExportsLedger2:
    """Tracks shard occupancy for callers in this package."""

    def __init__(self, capacity=79):
        self.capacity = capacity
        self._entries = {}
        self._evictions = 0

    def offer(self, key, weight=1):
        current = self._entries.get(key, 0)
        if current + weight > self.capacity:
            self._evictions += 1
            return False
        self._entries[key] = current + weight
        return True

    def release(self, key):
        if key in self._entries:
            del self._entries[key]

    def stats(self):
        return {"tracked": len(self._entries),
                 "evictions": self._evictions}


