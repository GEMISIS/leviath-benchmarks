#!/usr/bin/env python3
"""Generate analyst-bench-adversarial: the base agent plus a plan critic.

Generated rather than hand-maintained. It was hand-maintained once, and
the base agent then gained a region, a tool and two prompt changes that
never reached it - which is the same drift that left the scoped variant
without the critic and the critic without the scoping. A variant that
cannot fall behind its base is worth more than one that reads nicely.

The critic stage itself lives in parts/plan_review.toml. Everything else
is the base file with `plan`'s forward edge redirected through it.

Usage: python3 make_adversarial.py
Afterwards: make_scoped.py, make_mix.py, check_transforms.py, check_pairs.py
"""
from __future__ import annotations

import shutil
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = "analyst-bench"
DEST = "analyst-bench-adversarial"

base = (HERE / SOURCE / "agent.leviath").read_text()
critic = (HERE / "parts" / "plan_review.toml").read_text()

# `plan` hands to the critic instead of straight to `compute`. Only the
# header and hint change: the transform config on that edge is the base's,
# so a change to what crosses the edge does not have to be made twice.
old = '[stages.plan.transitions.compute]\nhint = "The plan is written - compute it"'
new = ('[stages.plan.transitions.plan_review]\n'
       'hint = "The plan is written - have it reviewed"')
if old not in base:
    raise SystemExit("base agent's plan->compute edge is not where expected")
text = base.replace(old, new, 1)
text = text.replace("[stages.plan.transitions.compute.transform_config]",
                    "[stages.plan.transitions.plan_review.transform_config]", 1)

# The critic stage goes in ahead of compute.
anchor = text.index("# ─── Stage 3")
text = text[:anchor] + critic + text[anchor:]

version = tomllib.loads(base)["agent"]["version"]
text = text.replace(f'version = "{version}"',
                    f'version = "{version}-adversarial"', 1)
_, _, rest = text.partition("[agent]")
text = (f"# Adversarial variant of {SOURCE}: the same agent with a plan critic\n"
        "# between planning and computing, on a different vendor's model.\n"
        "# GENERATED by make_adversarial.py - regenerate rather than editing.\n"
        "# The critic stage itself is parts/plan_review.toml.\n\n"
        "[agent]" + rest)

doc = tomllib.loads(text)
assert "plan_review" in doc["stages"], "critic stage did not land"
dest = HERE / DEST
dest.mkdir(exist_ok=True)
for extra in (HERE / SOURCE).iterdir():
    if extra.is_dir():
        shutil.copytree(extra, dest / extra.name, dirs_exist_ok=True)
(dest / "agent.leviath").write_text(text)
print(f"{DEST}: {len(doc['stages'])} stages, critic on "
      f"{doc['stages']['plan_review']['model']['models'][0]['model']}")
