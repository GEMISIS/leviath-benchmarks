#!/usr/bin/env python3
"""Generate the mixed-model variants of the structured agents.

A mix is the same agent - same stages, same prompts, same regions, same
tools - with a different model named on each stage. That is the whole
point of the comparison: any difference between a mix and a pinned arm
is the model assignment and nothing else, so the variants are generated
rather than hand-edited.

Assignments live in mixes.json, written out stage by stage: a mix is a
claim about which model does which job, and an inferred mapping would
make that claim unreadable.

Usage:
    python3 make_mix.py            # regenerate every mix
    python3 make_mix.py econ       # just one

Afterwards: check_pairs.py (the variants must satisfy the same policy).
"""
from __future__ import annotations

import json
import re
import shutil
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIXES = json.loads((HERE / "mixes.json").read_text())
_STAGE = re.compile(r"^\[stages\.([A-Za-z0-9_]+)\]\s*$")
_MODEL = re.compile(r"^model = \{ models = \[.*\] \}\s*$")


def _model_line(model_id: str) -> str:
    provider, _, model = model_id.partition("/")
    return ('model = { models = [{ provider = "%s", model = "%s" }] }\n'
            % (provider, model))


def render(agent: str, mix_name: str, assignment: dict[str, str]) -> str:
    """The agent's text with each stage's model line replaced."""
    text = (HERE / agent / "agent.leviath").read_text()
    doc = tomllib.loads(text)
    missing = set(doc["stages"]) - set(assignment)
    extra = set(assignment) - set(doc["stages"])
    if missing or extra:
        raise SystemExit(
            f"{mix_name}/{agent}: assignment does not match the agent's "
            f"stages (missing {sorted(missing)}, unknown {sorted(extra)})")

    out, stage = [], None
    for line in text.splitlines(keepends=True):
        m = _STAGE.match(line)
        if m:
            stage = m.group(1)
        elif _MODEL.match(line) and stage:
            line = _model_line(assignment[stage])
            stage = None          # only the stage's own model line
        out.append(line)
    body = "".join(out)

    header = (
        f"# {mix_name} mix of {agent}: identical shape, one model named "
        "per stage.\n"
        "# GENERATED by make_mix.py from mixes.json - do not edit by hand.\n"
        + "".join(f"#   {s:16} {assignment[s]}\n" for s in doc["stages"])
        + "\n")
    # Replace only the base agent's leading provenance block; every
    # comment further down explains a design decision and stays.
    lines = body.splitlines(keepends=True)
    start = 0
    for i, line in enumerate(lines):
        if line.strip() and not line.lstrip().startswith("#"):
            start = i
            break
    return header + "".join(lines[start:])


def main() -> int:
    wanted = sys.argv[1:] or [k for k in MIXES if not k.startswith("_")]
    for mix_name in wanted:
        spec = MIXES.get(mix_name)
        if not spec:
            raise SystemExit(f"no mix named {mix_name!r} in mixes.json")
        for agent, assignment in spec.items():
            if agent.startswith("_"):
                continue
            dest = HERE / f"{agent}-{mix_name}"
            dest.mkdir(exist_ok=True)
            text = render(agent, mix_name, assignment)
            tomllib.loads(text)   # must parse before it lands on disk
            (dest / "agent.leviath").write_text(text)
            src_tools = HERE / agent / "tools"
            dst_tools = dest / "tools"
            if dst_tools.is_dir():
                shutil.rmtree(dst_tools)
            if src_tools.is_dir():
                shutil.copytree(src_tools, dst_tools)
            models = sorted(set(assignment.values()))
            print(f"{dest.name}: {len(assignment)} stages, "
                  f"{len(models)} models ({', '.join(models)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
